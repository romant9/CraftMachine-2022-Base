public class Margin
{
	public float top;

	public float left;

	public float bottom;

	public float right;

	public Margin()
	{
		top = 0f;
		left = 0f;
		bottom = 0f;
		right = 0f;
	}

	public Margin(float top, float left, float bottom, float right)
	{
		this.top = top;
		this.left = left;
		this.bottom = bottom;
		this.right = right;
	}
}
